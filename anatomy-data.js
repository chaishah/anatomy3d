export function normalizeAnatomyName(value = '') {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .replace(/\b(left|right|l|r)\b/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function matchAnatomyInfo(name, kind = null) {
  const normalized = normalizeAnatomyName(name);
  if (!normalized) return null;

  const candidates = kind ? ANATOMY_INFO.filter((item) => item.kind === kind) : ANATOMY_INFO;
  let best = null;
  let bestLength = 0;

  for (const item of candidates) {
    for (const alias of item.aliases) {
      const normalizedAlias = normalizeAnatomyName(alias);
      if (!normalizedAlias) continue;
      if (normalized.includes(normalizedAlias) || normalizedAlias.includes(normalized)) {
        if (normalizedAlias.length > bestLength) {
          best = item;
          bestLength = normalizedAlias.length;
        }
      }
    }
  }

  return best;
}

export function infoById(id) {
  return ANATOMY_INFO.find((item) => item.id === id) || null;
}
